import ollama
from config import settings
from base import BaseProvider
import logging

class OllamaProvider(BaseProvider):         # Inherit from BaseProvider
    
    def __init__(self): 
        # both from config file
        self.model = settings.ollama_model
        self.base_url = settings.ollama_base_url
        self.logger = logging.getLogger(__name__)
        
        
    def generate(self, prompt:str) -> str:
        '''
        Generates a response from the Ollama API based on the provided prompt.
        Args:
            prompt (str): The input prompt to send to the Ollama API.
        Returns:
            str: The response generated by the Ollama API, or an error message if the API call fails.
        '''
        
        try:
            response = ollama.chat(
                model=self.model,
                messages=[{
                    "role":"user",
                    "content":prompt
                }]
            )
            
            self.logger.info(f"Ollama API response: {response}")
            
            return response["message"]["content"]
        
        except Exception as e:
            self.logger.error(f"Error calling Ollama API: {e}")
            return "Error: Unable to get response from Ollama API."
        
        
    