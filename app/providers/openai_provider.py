from openai import OpenAI
from config import settings

class OpenAIProvider:
    
    def __init__(self):
        
        self.model = settings.openai_model
        self.api_key = settings.openai_api_key
        
    def generate(self, prompt:str) -> str:
        '''
        Generates a response from the OpenAI API based on the provided prompt.
        Args:
            prompt (str): The input prompt to send to the OpenAI API.
        Returns:
            str: The response generated by the OpenAI API, or an error message if the API call fails.
        '''
        
        try:
            client = OpenAI(api_key=self.api_key)
            response = client.responses.create(
                model=self.model,
                input=prompt
            )
        except Exception as e:
            print(f"Error calling OpenAI API: {e}")
            return "Error: Unable to get response from OpenAI API."
        
        return response.output_text